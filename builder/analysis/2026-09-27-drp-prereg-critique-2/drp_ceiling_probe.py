def draw(rng, pool):
    seen, out = set(), []
    while len(out) < N_PAIRS:
        s, t = rng.sample(pool, 2)
        k = frozenset((s, t))
        if k in seen:
            continue
        seen.add(k)
        out.append((s, t))
    return out


