def bottleneck(s: int, t: int, excl: set[int]) -> float:
    """Minimax over interiors; direct edge forbidden; endpoints exempt; inf if none."""
    excl = set(excl) - {s, t}
    best = {}
    pq = []
    for w in nbr[off[s]:off[s + 1]]:
        if w == t or w in excl:
            continue
        lw = pl[w]
        if lw < best.get(w, 2.0):
            best[w] = lw
            heapq.heappush(pq, (lw, w))
    done = set()
    while pq:
        lu, u = heapq.heappop(pq)
        if u in done:
            continue
        done.add(u)
        row = nbr[off[u]:off[u + 1]]
        for w in row:
            if w == t:
                return lu  # u != s by construction; first popped neighbour of t is optimal
        for w in row:
            if w == s or w in excl or w in done:
                continue
            lw = lu if lu >= pl[w] else pl[w]
            if lw < best.get(w, 2.0):
                best[w] = lw
                heapq.heappush(pq, (lw, w))
    return float("inf")


# scipy adjacency for the independent check
A = sp.csr_matrix((np.ones(e, dtype=np.int8), store.neighbours.astype(np.int64),
                   store.offsets.astype(np.int64)), shape=(n, n))


def reachable_under(s: int, t: int, c: float, excl: set[int]) -> bool:
    keep = pctl <= c
    keep[[s, t]] = True
    if excl:
        keep[list(excl - {s, t})] = False
    idx = np.flatnonzero(keep)
    pos = -np.ones(n, dtype=np.int64)
    pos[idx] = np.arange(idx.size)
    data = A.data.copy()
    for a, b in ((s, t), (t, s)):
        lo, hi = A.indptr[a], A.indptr[a + 1]
        data[lo:hi][A.indices[lo:hi] == b] = 0
    full = sp.csr_matrix((data, A.indices, A.indptr), shape=(n, n))
    full.eliminate_zeros()
    sub = full[idx][:, idx]
    order = breadth_first_order(sub, int(pos[s]), directed=False, return_predecessors=False)
    return bool(np.isin(pos[t], order))


def check_b(s: int, t: int, b: float, excl: set[int]) -> bool:
    if not np.isfinite(b):
        return not reachable_under(s, t, 1.0, excl)
    i = int(np.searchsorted(distinct, b, side="left"))
    assert distinct[i] == b, "bottleneck is not a node percentile"
    ok_at = reachable_under(s, t, b, excl)
    ok_below = (not reachable_under(s, t, distinct[i - 1], excl)) if i > 0 else True
    return ok_at and ok_below


